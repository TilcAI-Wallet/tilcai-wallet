import { strict as assert } from "node:assert";
import { createHash, randomBytes, randomUUID } from "node:crypto";
import { test } from "node:test";
import pg from "pg";
import { makeTestEnvelope } from "./test-envelope.fixture.js";
import { loadTestnetEnvelope, storeTestnetEnvelope } from "./postgres-envelope-vault.js";

const databaseUrl=process.env.WALLET_TEST_DATABASE_URL;
test("PostgreSQL persists a single encrypted Testnet envelope and enforces lease fencing",{skip:!databaseUrl},async (t) => {
  const admin=new pg.Pool({connectionString:databaseUrl,max:1});
  const worker=new pg.Pool({connectionString:databaseUrl,options:"-c role=wallet_worker",max:2});
  const api=new pg.Pool({connectionString:databaseUrl,options:"-c role=wallet_api",max:1});
  t.after(async()=>{await worker.end();await api.end();await admin.end();});
  const suffix=randomUUID(), tenant=`vault-${suffix}`, session=`session-${suffix}`, card=`card-${suffix}`, order=`order-${suffix}`, attempt=`attempt-${suffix}`, event=`event-${suffix}`;
  await admin.query("INSERT INTO wallet_private.tenants(tenant_id) VALUES($1)",[tenant]);
  await admin.query("INSERT INTO wallet_private.sessions(tenant_id,network,session_id,actor_id,expires_at) VALUES($1,'testnet',$2,'actor',now()+interval '1 hour')",[tenant,session]);
  await admin.query("INSERT INTO wallet_private.cards(tenant_id,network,card_id,session_id,contract_id,asset_id,recipient,agent,mode) VALUES($1,'testnet',$2,$3,'test-contract','asset','recipient','agent','testnet')",[tenant,card,session]);
  await admin.query("INSERT INTO wallet_private.orders(tenant_id,network,order_id,card_id,session_id,offer_id,amount) VALUES($1,'testnet',$2,$3,$4,'test-report',5000000)",[tenant,order,card,session]);
  await admin.query("INSERT INTO wallet_private.attempts(tenant_id,network,order_id,attempt_id) VALUES($1,'testnet',$2,$3)",[tenant,order,attempt]);
  await admin.query("INSERT INTO wallet_private.outbox(tenant_id,network,event_id,order_id,kind) VALUES($1,'testnet',$2,$3,'payment')",[tenant,event,order]);
  await admin.query("INSERT INTO wallet_private.worker_assignments(login_name,tenant_id) SELECT session_user,$1",[tenant]);
  const sample=makeTestEnvelope(), {bytes,hash}=sample, key=randomBytes(32);
  await admin.query("UPDATE wallet_private.cards SET agent=$2,contract_id=$3 WHERE tenant_id=$1",[tenant,sample.agent,sample.contractId]);
  const context={keyId:"ephemeral-test-key",agent:sample.agent,tenantId:tenant,orderId:order,attemptId:attempt,contractId:sample.contractId,transactionHash:hash,validThroughLedger:123};
  const claimed=(await worker.query("SELECT * FROM wallet_private.claim_testnet(30)")).rows[0]; assert.ok(claimed);
  const lease={tenantId:tenant,eventId:event,token:claimed.lease_token};
  assert.equal(await storeTestnetEnvelope(worker,lease,context,key,bytes),true);
  assert.equal(await storeTestnetEnvelope(worker,lease,context,key,bytes),false);
  await assert.rejects(()=>api.query("SELECT * FROM wallet_private.encrypted_envelopes"));
  await assert.rejects(()=>worker.query("SELECT * FROM wallet_private.encrypted_envelopes"));
  const raw=await admin.query("SELECT ciphertext,xdr_digest FROM wallet_private.encrypted_envelopes WHERE tenant_id=$1",[tenant]);
  assert.notDeepEqual(raw.rows[0].ciphertext,bytes);
  assert.deepEqual(raw.rows[0].xdr_digest,createHash("sha256").update(bytes).digest());
  await admin.query("UPDATE wallet_private.outbox SET lease_until=now()-interval '1 second' WHERE tenant_id=$1",[tenant]);
  assert.equal(await loadTestnetEnvelope(worker,lease,attempt,async()=>key),null);
  const recovered=(await worker.query("SELECT * FROM wallet_private.claim_testnet(30)")).rows[0]; assert.ok(recovered);
  const newLease={...lease,token:recovered.lease_token};
  const loaded=await loadTestnetEnvelope(worker,newLease,attempt,async()=>key); assert.ok(loaded);
  assert.equal(loaded.context.transactionHash,hash); assert.deepEqual(loaded.envelope,bytes);
  await assert.rejects(()=>loadTestnetEnvelope(worker,newLease,attempt,async()=>randomBytes(32)));
  assert.equal(await loadTestnetEnvelope(worker,{...newLease,tenantId:"unassigned"},attempt,async()=>key),null);
});
