import { strict as assert } from "node:assert";
import { createHash, randomUUID } from "node:crypto";
import { test } from "node:test";
import pg from "pg";
import { createApi } from "./app.js";
import { processFixtureOnce } from "../../worker/src/fixture-worker.js";

const url = process.env.WALLET_TEST_DATABASE_URL;
test("PostgreSQL: credentials, tenant isolation, concurrent replay and reservation", { skip: !url }, async (t) => {
  const admin = new pg.Pool({ connectionString:url, max:1 });
  const runtime = new pg.Pool({ connectionString:url, options:"-c role=wallet_api", max:5 });
  const worker = new pg.Pool({ connectionString:url, options:"-c role=wallet_worker", max:2 });
  const app = createApi({ pool: runtime });
  t.after(async () => { await app.close(); await worker.end(); await runtime.end(); await admin.end(); });
  const suffix = randomUUID();
  const a = `tenant-a-${suffix}`, b = `tenant-b-${suffix}`, sa = `sa-${suffix}`, sb = `sb-${suffix}`, card = `card-${suffix}`;
  const token = `fixture_${randomUUID().replaceAll("-", "")}`, wrong = `fixture_${randomUUID().replaceAll("-", "")}`;
  const hash = (value: string) => createHash("sha256").update(value).digest();
  await admin.query("INSERT INTO wallet_private.tenants (tenant_id) VALUES ($1),($2)",[a,b]);
  await admin.query("INSERT INTO wallet_private.sessions (tenant_id,network,session_id,actor_id,expires_at) VALUES ($1,'testnet',$2,'actor',now()+interval '1 hour'),($3,'testnet',$4,'actor',now()+interval '1 hour')",[a,sa,b,sb]);
  await admin.query("INSERT INTO wallet_private.credentials (tenant_id,network,session_id,token_hash,scopes,expires_at) VALUES ($1,'testnet',$2,$3,ARRAY['sessions:read','cards:read','orders:write','orders:read','receipts:read'],now()+interval '1 hour'),($4,'testnet',$5,$6,ARRAY['cards:read'],now()-interval '1 second')",[a,sa,hash(token),b,sb,hash(wrong)]);
  await admin.query("INSERT INTO wallet_private.cards (tenant_id,network,card_id,session_id,contract_id,asset_id,recipient,agent,balance_minor,payment_limit_minor,total_limit_minor,spent_minor,mode) VALUES ($1,'testnet',$2,$3,'fixture-contract',$4,$5,'fixture-agent',200000000,5000000,5000000,0,'fixture')",[a,card,sa,"CBIELTK6YBZJU5UP2WWQEUCYKLPU6AUNZ2BQ4WWFEIE3USCIHMXQDAMA","GAGK4SEOVSZDQXSBMO6KMUHNH36B3E2AZFDINVDFVRVV2ZYLP577OSHX"]);
  const headers = {authorization:`Bearer ${token}`,"idempotency-key":"purchase-1"};
  const payload = {cardId:card,offerId:"test-report",maxAmountMinor:"5000000"};
  const [first,second] = await Promise.all([app.inject({method:"POST",url:"/v1/orders",headers,payload}),app.inject({method:"POST",url:"/v1/orders",headers,payload})]);
  assert.deepEqual([first.statusCode,second.statusCode].sort(),[200,202]);
  assert.equal(first.json().orderId,second.json().orderId);
  assert.equal((await app.inject({method:"POST",url:"/v1/orders",headers,payload:{...payload,maxAmountMinor:"5000001"}})).statusCode,409);
  const rows=await admin.query("SELECT (SELECT count(*) FROM wallet_private.orders WHERE tenant_id=$1)::int AS orders,(SELECT count(*) FROM wallet_private.holds WHERE tenant_id=$1)::int AS holds,(SELECT count(*) FROM wallet_private.attempts WHERE tenant_id=$1)::int AS attempts,(SELECT count(*) FROM wallet_private.outbox WHERE tenant_id=$1)::int AS events",[a]);
  assert.deepEqual(rows.rows[0],{orders:1,holds:1,attempts:1,events:1});
  await admin.query("INSERT INTO wallet_private.worker_assignments (login_name,tenant_id) SELECT session_user,$1",[a]);
  const [claim1,claim2] = await Promise.all([worker.query("SELECT * FROM wallet_private.claim_fixture(30)"),worker.query("SELECT * FROM wallet_private.claim_fixture(30)")]);
  assert.equal(claim1.rowCount! + claim2.rowCount!,1);
  const lease1 = claim1.rows[0] ?? claim2.rows[0];
  await admin.query("UPDATE wallet_private.outbox SET lease_until=now()-interval '1 second' WHERE tenant_id=$1",[a]);
  const lease2 = (await worker.query("SELECT * FROM wallet_private.claim_fixture(30)")).rows[0];
  assert.ok(lease2);
  const denied = await worker.query("SELECT wallet_private.advance_fixture($1,$2,$3,'prepare',$4,$5) AS ok",[a,lease1.event_id,lease1.lease_token,"a".repeat(64),Buffer.from("synthetic")]);
  assert.equal(denied.rows[0].ok,false);
  await assert.rejects(() => worker.query("SELECT * FROM wallet_private.worker_assignments"));
  await assert.rejects(() => worker.query("SELECT * FROM wallet_private.outbox"));
  const fakeEnvelope = Buffer.from(JSON.stringify(["tilcai-fixture-v1",lease2.order_id]));
  const fakeHash = createHash("sha256").update(fakeEnvelope).digest("hex");
  const advance = (step: string) => worker.query("SELECT wallet_private.advance_fixture($1,$2,$3,$4,$5,$6) AS ok",[a,lease2.event_id,lease2.lease_token,step,fakeHash,fakeEnvelope]);
  assert.equal((await advance("prepare")).rows[0].ok,true);
  // Crash before submission, reclaim, and submit exactly the stored synthetic payload.
  await admin.query("UPDATE wallet_private.outbox SET lease_until=now()-interval '1 second' WHERE tenant_id=$1",[a]);
  const lease3 = (await worker.query("SELECT * FROM wallet_private.claim_fixture(30)")).rows[0];
  assert.ok(lease3);
  const submit = await worker.query("SELECT wallet_private.advance_fixture($1,$2,$3,'submit',$4,$5) AS ok",[a,lease3.event_id,lease3.lease_token,fakeHash,fakeEnvelope]);
  assert.equal(submit.rows[0].ok,true);
  // Crash after submission; the next worker must reuse the persisted payload.
  await admin.query("UPDATE wallet_private.outbox SET lease_until=now()-interval '1 second' WHERE tenant_id=$1",[a]);
  assert.equal(await processFixtureOnce(worker,30),true);
  assert.equal(await processFixtureOnce(worker,30),false);
  const receipt = first.json().receiptId;
  const finalReceipt = await app.inject({method:"GET",url:`/v1/receipts/${receipt}`,headers});
  assert.equal(finalReceipt.statusCode,200);
  assert.equal(finalReceipt.json().mode,"fixture");
  assert.equal(finalReceipt.json().payment.status,"confirmed");
  assert.equal(finalReceipt.json().payment.txHash,fakeHash);
  const persisted = await admin.query("SELECT (SELECT count(*) FROM wallet_private.fixture_submissions WHERE tenant_id=$1)::int AS submissions,(SELECT count(*) FROM wallet_private.attempts WHERE tenant_id=$1)::int AS attempts",[a]);
  assert.deepEqual(persisted.rows[0],{submissions:1,attempts:1});
  assert.equal(finalReceipt.json().delivery.status,"pending");
  assert.equal((await app.inject({method:"GET",url:`/v1/orders/${first.json().orderId}`,headers})).json().status,"paid");
  await admin.query("UPDATE wallet_private.credentials SET revoked_at=now() WHERE tenant_id=$1",[a]);
  assert.equal((await app.inject({method:"GET",url:`/v1/cards/${card}`,headers})).statusCode,401);
  assert.equal((await app.inject({method:"GET",url:`/v1/sessions/${sb}`,headers})).statusCode,404);
  assert.equal((await app.inject({method:"GET",url:`/v1/cards/${card}`,headers:{authorization:`Bearer ${wrong}`}})).statusCode,401);
});
